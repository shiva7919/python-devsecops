# average of three numbers in the function // store average in the function and call the function 

def calc_avg(a,b,c):           # this are parameters  // a is first value and b is second value and c is third value 
    avg = (a+b+c)/3
    print("the average of",a,"and",b,"and",c,"is",avg)

calc_avg(2,3,4)  # Output: the average of 2 and 3 and 4 is 3    

calc_avg(20,30,40)  # Output: the average of 20 and 30 and 40 is 30

